    tl.to(".hero__name", { yPercent: -18, duration: 1 }, 0);
    tl.to(".hero__base", { opacity: 0, duration: 0.12 }, 0.72);
    tl.to(".hero__frame", { scale: () => (wide() ? 1.16 : 1), duration: 0.2, ease: "power2.in" }, 0.82);

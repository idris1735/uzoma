/* ============================================================
   home.js — front page sections, in document order:

     preloader  five silhouettes take their positions
     hero       pinned; artwork resolves through its four passes
     award      trophy rises, kinetic type lands
     about      shape swaps per paragraph, masked line reveals
     wall       full-bleed mosaic, columns parallax in opposition
     portfolio  pinned horizontal track, pointer-driven reveal
     boards     clips play on hover, or in view on touch
     conform    pointer position drives saturation
   ============================================================ */


    tl.to(".hero__pass--sil", { opacity: 0.16, duration: 0.14 }, 0.1);

    /* labels draw on while the line pass is showing */
    $$(".hero__annos .anno-item").forEach((item, idx) => {
      const at = 0.2 + idx * 0.085;
      tl.to(item, { opacity: 1, y: 0, duration: 0.05 }, at);
      tl.to($(".anno-item__leader", item), { scaleY: 1, duration: 0.045 }, at + 0.01);
      const marks = $$("svg > *", item);
      if (marks.length) tl.to(marks, { strokeDashoffset: 0, duration: 0.05, stagger: 0.02 }, at + 0.02);
      const name = $(".anno-item__name", item);
      if (name) {
        tl.call(() => typeOut(name), null, at + 0.03);
        /* five names side by side won't fit a phone, so they take turns:
           each types out while its mark draws, then hands over to the next.
           classList in a tl.call — GSAP's className +=/-= syntax writes the
           literal operator string into the attribute instead of toggling. */
        if (window.innerWidth < 641) {
          tl.call(() => item.classList.add("is-active"), null, at);
          tl.call(() => item.classList.remove("is-active"), null, at + 0.1);
        }
      }
    });

    /* pass 2 -> 3: flats wipe in bottom to top */
    tl.to(".hero__pass--flat", { clipPath: "inset(0% 0% 0% 0%)", duration: 0.17, ease: "power2.inOut" }, 0.4);

    /* pass 3 -> 4: render wipes in right to left */
    tl.to(".hero__pass--final", { clipPath: "inset(0% 0% 0% 0%)", duration: 0.2, ease: "power2.inOut" }, 0.62);
    tl.to(".hero__pass--sil", { opacity: 0, duration: 0.08 }, 0.62);

